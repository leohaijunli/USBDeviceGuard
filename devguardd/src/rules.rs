//! udev rule generation.  Pure text building plus strict value escaping so a
//! serial number or path from the world can never inject a udev operator.
//!
//! The daemon writes `/etc/udev/rules.d/90-devguard.rules`; rules only set
//! symlinks, group, mode, the ModemManager ignore flag and the systemd
//! one-shot trigger — long work belongs to `devguard-apply@.service`.

use devguard_core::{config::DeviceConfig, config::IdRole};
use devguard_core::util::{normalize_hex4, parse_mode, validate_group, validate_name};

pub const RULES_HEADER: &str = "# Generated by devguardd. Edits are overwritten; change device TOMLs instead.";

/// Characters allowed inside a udev match value.  Everything that udev treats
/// specially (`"`, `%`, `$`, `\`, whitespace, comparisons) is excluded, and
/// values are additionally checked for length.
fn safe_value(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 128
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"._:-".contains(&b))
}

fn quote(value: &str) -> String {
    format!("\"{value}\"")
}

fn id_match(id: &devguard_core::DeviceId) -> Option<String> {
    let vid = normalize_hex4(&id.vid).ok()?;
    let pid = normalize_hex4(&id.pid).ok()?;
    let mut terms = vec![
        format!("ATTRS{{idVendor}}=={}", quote(&vid)),
        format!("ATTRS{{idProduct}}=={}", quote(&pid)),
    ];
    match (&id.serial, &id.path) {
        (Some(serial), _) if safe_value(serial.trim()) => {
            terms.push(format!("ATTRS{{serial}}=={}", quote(serial.trim())));
        }
        (None, Some(path)) if safe_value(path.trim()) => {
            terms.push(format!("ENV{{ID_PATH}}=={}", quote(path.trim())));
        }
        // Neither a safe serial nor a safe path: this id cannot be matched
        // safely, and the caller reports it instead of emitting a loose rule.
        _ => return None,
    }
    Some(terms.join(", "))
}

/// One rule line per id; `role` is kept in a comment for auditability.
fn rule_for(device: &DeviceConfig, id: &devguard_core::DeviceId, group: &str) -> Option<String> {
    validate_name(&device.name).ok()?;
    let group = if device.access.group == "auto" { group } else { &device.access.group };
    validate_group(group).ok()?;
    if group == "auto" {
        return None;
    }
    let mode = parse_mode(&device.access.mode).ok()?;
    let matches = id_match(id)?;
    let symlink = format!("devguard/{}", device.name);
    Some(format!(
        "SUBSYSTEM==\"tty\", KERNEL==\"ttyACM[0-9]*|ttyUSB[0-9]*\", {}, SYMLINK+={}, GROUP={}, MODE={}, ENV{{ID_MM_DEVICE_IGNORE}}=\"1\", TAG+=\"systemd\", ENV{{SYSTEMD_WANTS}}=\"devguard-apply@%k.service\"",
        matches,
        quote(&symlink),
        quote(group),
        quote(&devguard_core::util::format_mode(mode)),
    ))
}

pub struct GeneratedRules {
    pub text: String,
    /// Ids that could not be matched safely; the daemon journals these.
    pub skipped: Vec<String>,
}

pub fn generate(devices: &[DeviceConfig], resolved_group: &str) -> GeneratedRules {
    let mut body = String::new();
    let mut skipped = Vec::new();
    for device in devices {
        let role_note = |id: &devguard_core::DeviceId| match id.role {
            IdRole::App => "app",
            IdRole::Bootloader => "bootloader",
        };
        let mut wrote = false;
        for id in &device.ids {
            match rule_for(device, id, resolved_group) {
                Some(line) => {
                    body.push_str(&format!(
                        "# {}:{} ({})\n{}\n\n",
                        device.name, id_binding(id), role_note(id), line
                    ));
                    wrote = true;
                }
                None => skipped.push(format!(
                    "{}: {}:{} ({}) has no safely matchable serial/path",
                    device.name,
                    id.vid,
                    id.pid,
                    role_note(id)
                )),
            }
        }
        if !wrote {
            skipped.push(format!("{}: no usable ids", device.name));
        }
    }
    let mut text = String::from(RULES_HEADER);
    text.push_str("\n\n");
    text.push_str(&body);
    GeneratedRules { text, skipped }
}

fn id_binding(id: &devguard_core::DeviceId) -> &'static str {
    if id.serial.is_some() {
        "serial"
    } else {
        "path"
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use devguard_core::config::{AccessConfig, DeviceId, SerialConfig};

    fn device(name: &str, ids: Vec<DeviceId>) -> DeviceConfig {
        DeviceConfig {
            name: name.to_owned(),
            kind: devguard_core::DeviceKind::Px4,
            description: None,
            ids,
            serial: SerialConfig::default(),
            access: AccessConfig::default(),
        }
    }

    fn px4() -> DeviceConfig {
        device(
            "px4-main",
            vec![
                DeviceId {
                    vid: "26ac".into(),
                    pid: "0032".into(),
                    serial: Some("0A1B2C3D".into()),
                    path: None,
                    role: IdRole::App,
                },
                DeviceId {
                    vid: "26ac".into(),
                    pid: "0011".into(),
                    serial: Some("0A1B2C3D".into()),
                    path: None,
                    role: IdRole::Bootloader,
                },
            ],
        )
    }

    #[test]
    fn app_and_bootloader_ids_share_one_symlink() {
        let generated = generate(&[px4()], "dialout");
        assert!(generated.skipped.is_empty(), "{:?}", generated.skipped);
        assert_eq!(
            generated.text.matches("SYMLINK+=\"devguard/px4-main\"").count(),
            2,
            "{}",
            generated.text
        );
        assert!(generated.text.contains("ATTRS{idVendor}==\"26ac\""));
        assert!(generated.text.contains("ATTRS{idProduct}==\"0032\""));
        assert!(generated.text.contains("ATTRS{idProduct}==\"0011\""));
        assert!(generated.text.contains("ATTRS{serial}==\"0A1B2C3D\""));
        assert!(generated.text.contains("GROUP=\"dialout\""));
        assert!(generated.text.contains("MODE=\"0660\""));
        assert!(generated.text.contains("ENV{ID_MM_DEVICE_IGNORE}=\"1\""));
        assert!(generated
            .text
            .contains("ENV{SYSTEMD_WANTS}=\"devguard-apply@%k.service\""));
        // The bootloader id is labelled for auditability.
        assert!(generated.text.contains("(bootloader)"));
        assert!(generated.text.contains("(app)"));
    }

    #[test]
    fn path_bound_ids_use_id_path() {
        let radio = device(
            "radio-1",
            vec![DeviceId {
                vid: "1a86".into(),
                pid: "7523".into(),
                serial: None,
                path: Some("pci-0000:00:14.0-usb-0:2:1.0".into()),
                role: IdRole::App,
            }],
        );
        let generated = generate(&[radio], "uucp");
        assert!(generated.text.contains("ENV{ID_PATH}==\"pci-0000:00:14.0-usb-0:2:1.0\""));
        assert!(!generated.text.contains("ATTRS{serial}"));
        assert!(generated.text.contains("GROUP=\"uucp\""));
    }

    #[test]
    fn unsafe_values_are_skipped_never_injected() {
        // A malicious serial must not produce a loose rule or a broken line.
        let evil = device(
            "px4-main",
            vec![DeviceId {
                vid: "26ac".into(),
                pid: "0032".into(),
                serial: Some("\"); SYMLINK+=\"/dev/all".into()),
                path: None,
                role: IdRole::App,
            }],
        );
        let generated = generate(&[evil], "dialout");
        // The header-only text plus a per-device "no usable ids" note.
        assert!(generated
            .skipped
            .iter()
            .any(|note| note.contains("no safely matchable") || note.contains("no usable ids")));
        assert!(!generated.text.contains("evil"));
        assert!(!generated.text.contains("ATTRS{serial}"));

        // An id with neither binding is skipped too.
        let loose = device(
            "loose",
            vec![DeviceId {
                vid: "26ac".into(),
                pid: "0032".into(),
                serial: None,
                path: None,
                role: IdRole::App,
            }],
        );
        let generated = generate(&[loose], "dialout");
        assert!(generated
            .skipped
            .iter()
            .any(|note| note.contains("no safely matchable")));
    }

    #[test]
    fn empty_store_yields_header_only() {
        let generated = generate(&[], "dialout");
        assert_eq!(generated.text.trim_end(), RULES_HEADER);
        assert!(generated.skipped.is_empty());
    }

    #[test]
    fn every_rule_is_limited_to_usb_serial_tty_nodes() {
        let generated = generate(&[px4()], "dialout");
        for line in generated.text.lines().filter(|line| !line.is_empty() && !line.starts_with('#')) {
            assert!(line.starts_with("SUBSYSTEM==\"tty\", KERNEL==\"ttyACM[0-9]*|ttyUSB[0-9]*\","), "{line}");
        }
    }

    #[test]
    fn explicit_device_group_is_not_replaced_by_the_auto_group() {
        let mut device = px4();
        device.access.group = "uucp".into();
        let generated = generate(&[device], "dialout");
        assert!(generated.text.contains("GROUP=\"uucp\""));
        assert!(!generated.text.contains("GROUP=\"dialout\""));
    }

    #[test]
    fn unsafe_serial_does_not_fall_back_to_a_safe_path() {
        let mut device = px4();
        device.ids.truncate(1);
        device.ids[0].serial = Some("unsafe*serial".into());
        device.ids[0].path = Some("pci-port-1".into());
        let generated = generate(&[device], "dialout");
        assert!(!generated.skipped.is_empty());
        assert!(!generated.text.contains("SYMLINK+="));
    }

    #[test]
    fn invalid_names_groups_modes_and_usb_ids_never_enter_rules() {
        for field in ["name", "group", "mode", "vid"] {
            let mut device = px4();
            match field {
                "name" => device.name = "../escape".into(),
                "group" => device.access.group = "dialout\", OWNER=\"attacker".into(),
                "mode" => device.access.mode = "0666".into(),
                "vid" => {
                    for id in &mut device.ids {
                        id.vid = "*".into();
                    }
                }
                _ => unreachable!(),
            }
            let generated = generate(&[device], "dialout");
            assert!(!generated.skipped.is_empty(), "{field}");
            assert!(!generated.text.contains("SYMLINK+="), "{field}");
        }
    }
}
